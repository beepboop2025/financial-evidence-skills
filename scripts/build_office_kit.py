#!/usr/bin/env python3
"""Build the office kit and single-file Google script; no product data included."""
import argparse
import hashlib
import io
from pathlib import Path
from zipfile import ZipFile, ZipInfo, ZIP_DEFLATED

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "docs/office"
FILES = ("office-core.js", "workbook.js", "refresh.mjs", "setup.md", "compatibility.json",
         "FinancialEvidenceFunding.pq", "FinancialEvidenceWatchlist.pq")


def build():
    script = b"// Generated by scripts/build_office_kit.py. Paste this whole file into Apps Script.\n"
    script += (DEST / "office-core.js").read_bytes() + b"\n"
    script += (ROOT / "integrations/google-sheets/office-adapter.gs").read_bytes()
    copies = {"FinancialEvidenceOffice.gs": script,
              "FinancialEvidenceRows.pq": (ROOT / "docs/tools/FinancialEvidenceRows.pq").read_bytes()}
    entries = {name: (DEST / name).read_bytes() for name in FILES}
    entries.update(copies)
    entries["LICENSE"] = (ROOT / "LICENSE").read_bytes()
    checksums = "".join(f"{hashlib.sha256(data).hexdigest()}  {name}\n" for name, data in sorted(entries.items())).encode()
    entries["SHA256SUMS"] = checksums
    output = io.BytesIO()
    with ZipFile(output, "w") as archive:
        for name, data in sorted(entries.items()):
            info = ZipInfo("financial-evidence-office/" + name, (2026, 10, 18, 0, 0, 0))
            info.compress_type = ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            archive.writestr(info, data)
    return {**copies, "SHA256SUMS": checksums, "office-kit.zip": output.getvalue()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, data in build().items():
        path = DEST / name
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f"Stale office asset: {name}; run scripts/build_office_kit.py")
        else:
            path.write_bytes(data)
    print("Office kit matches source" if args.check else "Built office kit")


if __name__ == "__main__":
    main()
