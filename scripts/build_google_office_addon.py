#!/usr/bin/env python3
"""Build a reproducible Google Editor add-on source package; never deploy it."""
import argparse
import hashlib
import io
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "docs/office/marketplaces/google"


def build():
    code = b"// Generated by scripts/build_google_office_addon.py.\n/** @OnlyCurrentDoc */\n"
    code += (ROOT / "docs/office/office-core.js").read_bytes() + b"\n" + (DEST / "Addon.gs").read_bytes()
    entries = {"Code.gs": code}
    entries.update({name: (DEST / name).read_bytes() for name in ("Sidebar.html", "appsscript.json", "README.md")})
    entries["LICENSE"] = (ROOT / "LICENSE").read_bytes()
    checksums = "".join(f"{hashlib.sha256(value).hexdigest()}  {name}\n" for name, value in sorted(entries.items())).encode()
    entries["SHA256SUMS"] = checksums
    archive_bytes = io.BytesIO()
    with ZipFile(archive_bytes, "w") as archive:
        for name, value in sorted(entries.items()):
            info = ZipInfo("financial-evidence-sheets-addon/" + name, (2026, 10, 18, 0, 0, 0))
            info.compress_type = ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            archive.writestr(info, value)
    return {"Code.gs": code, "SHA256SUMS": checksums, "google-editor-addon.zip": archive_bytes.getvalue()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, data in build().items():
        target = DEST / name
        if args.check:
            if not target.exists() or target.read_bytes() != data:
                raise SystemExit(f"Stale Google add-on asset: {name}; run scripts/build_google_office_addon.py")
        else:
            target.write_bytes(data)
    print("Google add-on package matches source" if args.check else "Built Google add-on package")


if __name__ == "__main__":
    main()
